/**
 * Просьба создать карточку товара в сообщении продавца.
 *
 * Понимает просьбу в начале («Создай карточку: кроссовки Nike, 7990 ₽») и в
 * любом месте («Вот кроссовки Nike, 42 размер, 7990 ₽, оформи карточку»).
 * Возвращает текст о товаре без самой просьбы. В середине сообщения нужна
 * именно «карточка» или «объявление»: «сделай товар дешевле» и «оформи товар
 * в корзину» просьбой о карточке не считаются. Чистый модуль без импортов.
 */

const START =
  /^(?:светлана[\s,!.:]*)?(?:пожалуйста[\s,]*)?(?:(?:созда(?:й|йте)|оформ(?:и|ите)|вылож(?:и|ите)|состав(?:ь|ьте))\s+(?:мне\s+|пожалуйста\s+)?(?:нов(?:ую|ый|ое)\s+)?(?:карточк[а-яё]*|товар[а-яё]*|объявлени[а-яё]*)|сдела(?:й|йте)\s+(?:мне\s+|пожалуйста\s+)?(?:нов(?:ую|ое)\s+)?(?:карточк[а-яё]*|объявлени[а-яё]*))(?:\s+(?:товара|на|для))?\s*[:—–-]?\s*/i;

const INSIDE =
  /(?:^|[\s,.!?;:—–-]+)(?:пожалуйста[\s,]+)?(?:созда(?:й|йте)|оформ(?:и|ите)|вылож(?:и|ите)|состав(?:ь|ьте)|сдела(?:й|йте))\s+(?:мне\s+|пожалуйста\s+)?(?:из\s+этого\s+|на\s+(?:это|него|неё|нее|них)\s+)?(?:нов(?:ую|ое)\s+)?(?:карточк[а-яё]*|объявлени[а-яё]*)(?:\s+товара)?(?:[\s,]+пожалуйста)?\s*[:—–-]?\s*/i;

const NOT_A_CARD = /в корзин|в избранн/i;
const LEAD = /^(?:(?:привет|здравствуйте|добрый\s+(?:день|вечер)|доброе\s+утро|светлана)[\s,!.:]*)+(?:(?:вот|это|у\s+меня|есть|продаю|продам)\s+)?/i;

export interface DraftCommand {
  /** Текст о товаре без просьбы, может быть пустым. */
  product: string;
  /** Просьба стоит в начале сообщения. */
  atStart: boolean;
}

export function parseDraftCommand(message: string): DraftCommand | null {
  const t = message.replace(/\r/g, "").trim();
  if (!t || NOT_A_CARD.test(t)) return null;
  const start = START.exec(t);
  if (start) return { product: t.slice(start[0].length).trim(), atStart: true };
  const inside = INSIDE.exec(t);
  if (!inside) return null;
  const before = t.slice(0, inside.index).trim().replace(LEAD, "").replace(/^(?:вот|это|у\s+меня|есть)\s+/i, "");
  const after = t.slice(inside.index + inside[0].length).trim();
  const product = [before, after]
    .map((part) => part.replace(/^[\s,.;:!?—–-]+|[\s,.;:!?—–-]+$/g, ""))
    .filter(Boolean)
    .join(", ");
  return { product, atStart: false };
}
