/**
 * «Что мне сделать сегодня?»: Светлана отвечает списком дел. Продавцу тем же
 * списком, что и блок «Что сделать сегодня» на главной кабинета, покупателю
 * его заказами, которые ждут действия. Каждое дело ссылкой на нужную страницу.
 */

const TODAY = /(?:что\s+(?:мне\s+)?(?:нужно\s+|надо\s+|стоит\s+)?(?:с?делать|успеть)\s+сегодня|какие\s+(?:у\s+меня\s+)?(?:дела|задачи)(?:\s+на)?\s+сегодня|что\s+(?:у\s+меня\s+)?(?:срочного|горит)|с\s+чего\s+начать\s+(?:день|сегодня)|план\s+на\s+сегодня)/i;

export function isTodayQuestion(text: string): boolean {
  return TODAY.test(text);
}

export const TODAY_REPLY = "Смотрю, что ждёт вас сегодня.";

export const SELLER_TODAY_EMPTY =
  "Срочных дел нет: новых заказов, сообщений и споров нет, с остатками и скидками всё в порядке. Хорошее время добавить товар или запустить скидку.";

export const BUYER_TODAY_EMPTY =
  "По заказам срочных дел нет: всё оплачено, ничего не ждёт выдачи. Могу подобрать товар или подарок, напишите, что ищете.";

/** Ответ Светланы: дела по порядку важности, каждое ссылкой. */
export function todayAnswer(items: readonly { text: string; href: string }[], empty: string = SELLER_TODAY_EMPTY): string {
  if (items.length === 0) return empty;
  const lines = items.map((item, i) => `${i + 1}. [${item.text}](${item.href})`);
  return ["Вот что стоит сделать сегодня, по порядку:", ...lines].join("\n");
}
