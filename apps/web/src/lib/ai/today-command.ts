/**
 * «Что мне сделать сегодня?»: продавец спрашивает Светлану, и она отвечает
 * тем же списком, что и блок «Что сделать сегодня» на главной кабинета,
 * со ссылками на нужные разделы.
 */
import type { TodoItem } from "../seller-todo";

const TODAY = /(?:что\s+(?:мне\s+)?(?:нужно\s+|надо\s+|стоит\s+)?(?:с?делать|успеть)\s+сегодня|какие\s+(?:у\s+меня\s+)?(?:дела|задачи)(?:\s+на)?\s+сегодня|что\s+(?:у\s+меня\s+)?(?:срочного|горит)|с\s+чего\s+начать\s+(?:день|сегодня)|план\s+на\s+сегодня)/i;

export function isTodayQuestion(text: string): boolean {
  return TODAY.test(text);
}

export const TODAY_REPLY = "Смотрю, что ждёт вас сегодня.";

/** Ответ Светланы: дела по порядку важности, каждое ссылкой на раздел. */
export function todayAnswer(items: readonly TodoItem[]): string {
  if (items.length === 0) {
    return "Срочных дел нет: новых заказов, сообщений и споров нет, с остатками и скидками всё в порядке. Хорошее время добавить товар или запустить скидку.";
  }
  const lines = items.map((item, i) => `${i + 1}. [${item.text}](${item.href})`);
  return ["Вот что стоит сделать сегодня, по порядку:", ...lines].join("\n");
}
